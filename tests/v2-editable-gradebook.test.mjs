import test from 'node:test';
import assert from 'node:assert/strict';
import {createStore} from '../v2/store.mjs';
import {createWorkspace} from '../v2/workspace.mjs';
import {renderPage} from '../v2/views.mjs';
import {entryKey,canEnter,entryValue,decodeEntry,entryPreview,liveSummary,blockEntries,selectionBounds} from '../v2/gradebook-entry.mjs';
const cls='11-maths-1',eid='P121@11-maths',a1='11-maths-A1',a4='11-maths-A4';
const book=(s,staff='sam',scope='faculty')=>createWorkspace(s,staff,scope).markbook(cls);
const state={page:'classes',classId:cls,classTab:'markbook',unitId:'',query:'',flag:'all',below:false,sorts:{}};
const cell=(b,id,e=eid)=>{const o=b.overview(''),a=o.assessments.find(a=>a.id===id),p=o.rows.find(p=>p.enrolmentId===e);return {a,p,r:p.results[id]};};
test('inline gradebook uses assessment-specific boundaries, preserves zero and distinguishes absence',()=>{
 const s=createStore(),b=book(s),{a,p,r}=cell(b,a1);
 assert.ok(canEnter(a,r));
 const zero=decodeEntry(a,r,'0'),absent=decodeEntry(a,r,'A'),blank=decodeEntry(a,r,'');
 assert.equal(entryPreview(a,r,zero).percent,0);
 assert.equal(entryPreview(a,r,zero).grade,'U');
 assert.equal(absent.status,'absent');assert.equal(blank.status,'missing');
 assert.throws(()=>decodeEntry(a,r,'41'),/between/);
 const edit=decodeEntry(a,r,'40'),preview=entryPreview(a,r,edit);
 const live=liveSummary(p.summary,new Map([[a.id,preview]]),{bands:b.defaultBands});
 s.saveGradebookBatch('sam',cls,[edit],{confirmed:true,expectedRevision:0});
 const actual=s.analytics().studentSummary(eid);
 assert.equal(live.average,actual.average);assert.equal(live.grade,actual.grade);
 assert.equal(live.scored,actual.coverage.scored);
 assert.equal(entryValue(a,cell(book(s),a1).r),'40');
});
test('multiple assessments save atomically, with confirmation for clears and revision protection',()=>{
 const s=createStore(),b=book(s),x=cell(b,a1),y=cell(b,a4,'P123@11-maths');
 const edits=[decodeEntry(x.a,x.r,'39'),decodeEntry(y.a,y.r,'20')];
 const before=s.snapshot();
 assert.throws(()=>s.saveGradebookBatch('sam',cls,[edits[0],{...edits[1],marks:{total:99}}],{confirmed:true}),/Invalid mark/);
 assert.deepEqual(s.snapshot(),before);
 assert.throws(()=>s.saveGradebookBatch('avery',cls,edits,{confirmed:true}),/assigned teaching staff/);
 s.saveGradebookBatch('sam',cls,edits,{confirmed:true,expectedRevision:0});
 assert.equal(s.revision(),1);
 assert.equal(s.analytics().resultFor(a1,eid).rawMark,39);
 assert.equal(s.analytics().resultFor(a4,'P123@11-maths').rawMark,20);
 assert.equal(s.snapshot().audit.at(-1).action,'saveGradebookBatch');
 assert.throws(()=>s.saveGradebookBatch('sam',cls,edits,{confirmed:true,expectedRevision:0}),/changed since/);
 const blank=decodeEntry(x.a,cell(book(s),a1).r,'');
 assert.throws(()=>s.saveGradebookBatch('sam',cls,[blank],{confirmed:true}),/Confirm clearing/);
 s.saveGradebookBatch('sam',cls,[blank],{confirmed:true,confirmClear:true});
 assert.equal(s.analytics().resultFor(a1,eid).status,'missing');
});
test('draft/diagnostic results do not enter live overall grade; structured and read-only cells cannot be overwritten',()=>{
 const s=createStore(),b=book(s),x=cell(b,a4,'P123@11-maths'),p=x.p;
 const live=liveSummary(p.summary,new Map([[a4,entryPreview(x.a,x.r,decodeEntry(x.a,x.r,'20'))]]),{bands:b.defaultBands});
 assert.equal(live.average,p.summary.average);
 const q=cell(b,'11-maths-A3');assert.equal(canEnter(q.a,q.r),false);
 const ro=cell(book(s,'avery','school'),a1);assert.equal(canEnter(ro.a,ro.r),false);
 assert.throws(()=>decodeEntry(q.a,q.r,'1'),/read-only/);
 assert.match(renderPage(createWorkspace(s,'sam','faculty'),state),/class="gradebook-cell"/);
 assert.doesNotMatch(renderPage(createWorkspace(s,'avery','school'),state),/class="gradebook-cell"/);
 s.setStudentExclusion('sam',a1,eid,{excluded:true,reason:'Demo exclusion',confirmed:true});
 const excluded=cell(book(s),a1);assert.equal(canEnter(excluded.a,excluded.r),false);
});
test('clipboard blocks reject structured cells and invalid values atomically; selection rectangle is stable',()=>{
 const b=book(createStore()),o=b.overview('');
 const col=o.assessments.findIndex(a=>a.id===a1);
 assert.equal(blockEntries(o,0,col,'12\n13').length,2);
 assert.throws(()=>blockEntries(o,0,col,'12\t13'),/read-only or structured/);
 assert.throws(()=>blockEntries(o,0,col,'12\n999'),/between/);
 assert.deepEqual(selectionBounds({row:4,col:3},{row:1,col:0}),{top:1,bottom:4,left:0,right:3});
});
