const create=()=>createStore({clock:()=> '2026-11-24T08:00:00.000Z'});
const state=(page='home',extra={})=>({page,classId:null,query:'',flag:'all',below:false,caseFilter:'active',caseClass:null,sorts:{},noticeFilter:'active',deadlineFilter:'open',...extra});
const notice=(overrides={})=>({title:'Example faculty update',body:'Fictional moderation reminder',kind:'notice',priority:'important',audience:{type:'faculty',id:'mathematics'},publishedDate:'2026-11-24',expiryDate:'2026-12-03',pinned:true,requiresAcknowledgement:true,links:[],...overrides});
const deadline=(overrides={})=>({title:'Example reporting checkpoint',event:'Reports',dueDate:'2026-11-30',details:'Personal reminder only',audience:{type:'faculty',id:'mathematics'},...overrides});
const find=(store,table,title)=>store.snapshot()[table].find(r=>r.title===title);
const w=(s,id='sam',scope)=>createWorkspace(s,id,scope);
test('publish permissions follow assigned responsibilities, not a broader viewing scope',()=>{
 const s=create(),data=s.snapshot(),sam=communicationPolicy(data,'sam'),morgan=communicationPolicy(data,'morgan'),avery=communicationPolicy(data,'avery');
 assert.equal(sam.canPublish({type:'faculty',id:'mathematics'}),true);
 assert.equal(sam.canPublish({type:'faculty',id:'science'}),false);
 assert.equal(sam.canPublish({type:'all',id:null}),false);
 assert.equal(morgan.canPublish({type:'house',id:'willow'}),true);
 assert.equal(morgan.canPublish({type:'house',id:'cedar'}),false);
 assert.equal(avery.canPublish({type:'all',id:null}),true);
 assert.equal(avery.canPublish({type:'year',id:99}),false);
 assert.throws(()=>s.saveNotice('jordan',null,notice()),/cannot publish/);
 assert.throws(()=>s.saveNotice('sam',null,notice({audience:{type:'faculty',id:'science'}})),/cannot publish/);
 assert.equal(s.revision(),0);
});
test('publication updates relevant Home and Notices records and excludes unrelated staff',()=>{
 const s=create();s.saveNotice('sam',null,notice());
 const n=find(s,'notices','Example faculty update'),sam=w(s),jordan=w(s,'jordan'),outsider=s.snapshot().staff.find(p=>!communicationPolicy(s.snapshot(),p.id).recipient(n.audience)&&!p.roles.includes('leadership'));
 assert.ok(outsider);
 assert.ok(sam.home().notices.some(r=>r.id===n.id));
 assert.ok(jordan.home().pendingAcknowledgements.some(r=>r.id===n.id));
 assert.ok(renderPage(jordan,state('notices')).includes(n.title));
 assert.ok(renderPage(jordan,state()).includes(n.title));
 assert.equal(w(s,outsider.id).communications().notices.some(r=>r.id===n.id),false);
 assert.throws(()=>w(s,outsider.id).noticeDetail(n.id),/outside/);
 assert.equal(w(s,'avery').noticeDetail(n.id).recipient,false);
 assert.equal(w(s,'avery').noticeDetail(n.id).canAcknowledge,false);
 assert.throws(()=>s.acknowledgeNotice('avery',n.id),/No pending/);
});
test('acknowledgements are personal, versioned, audited and reset only after a confirmed edit',()=>{
 const s=create();s.saveNotice('sam',null,notice());const n=find(s,'notices','Example faculty update');
 const before=w(s,'jordan').communications().pendingAcknowledgements.length;
 s.acknowledgeNotice('jordan',n.id);
 assert.equal(w(s,'jordan').noticeDetail(n.id).acknowledged,true);
 assert.equal(w(s,'jordan').communications().pendingAcknowledgements.length,before-1);
 assert.equal(w(s,'sam').noticeDetail(n.id).acknowledged,false);
 assert.equal(w(s,'sam').noticeDetail(n.id).acknowledgementCount.done,1);
 assert.throws(()=>s.acknowledgeNotice('jordan',n.id),/No pending/);
 assert.throws(()=>s.saveNotice('jordan',n.id,notice({body:'Changed',confirmed:true})),/authorised/);
 assert.throws(()=>s.saveNotice('sam',n.id,notice({body:'Changed'})),/Confirm/);
 s.saveNotice('sam',n.id,notice({body:'Changed',confirmed:true}));
 const updated=w(s,'jordan').noticeDetail(n.id);
 assert.equal(updated.version,2);assert.equal(updated.acknowledged,false);assert.equal(updated.canAcknowledge,true);
 assert.equal(w(s,'sam').noticeDetail(n.id).acknowledgementCount.done,0);
 assert.ok(s.snapshot().audit.some(a=>a.action==='editNotice'&&a.before.acknowledgements.length===1&&a.after.acknowledgements.length===0));
 assert.match(renderDetail(w(s,'jordan'),{kind:'notice',id:n.id}),/Acknowledge notice/);
});
