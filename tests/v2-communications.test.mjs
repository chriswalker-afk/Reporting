test('central deadlines update all relevant views, personal completion does not affect other users',()=>{
 const s=create();
 assert.throws(()=>s.saveDeadline('sam',null,deadline()),/Only school leadership/);
 s.saveDeadline('avery',null,deadline());
 const d=find(s,'deadlines','Example reporting checkpoint');
 assert.ok(w(s).communications().openDeadlines.some(x=>x.id===d.id));
 assert.ok(w(s,'jordan').home().deadlines.some(x=>x.id===d.id));
 assert.match(renderPage(w(s,'avery'),state('notices')),/Example reporting checkpoint/);
 assert.equal(w(s,'avery').deadlineDetail(d.id).recipient,false);
 assert.throws(()=>s.setDeadlineCompletion('avery',d.id,true),/not assigned/);
 s.setDeadlineCompletion('sam',d.id,true);
 assert.equal(w(s).deadlineDetail(d.id).completed,true);
 assert.equal(w(s,'jordan').deadlineDetail(d.id).completed,false);
 assert.ok(!w(s).communications().openDeadlines.some(x=>x.id===d.id));
 assert.match(renderPage(w(s),state('notices',{deadlineFilter:'completed'})),/Example reporting checkpoint/);
 s.setDeadlineCompletion('sam',d.id,false);
 assert.equal(w(s).deadlineDetail(d.id).completed,false);
 s.setDeadlineCompletion('sam',d.id,true);
 assert.throws(()=>s.saveDeadline('avery',d.id,deadline({dueDate:'2026-12-09'})),/Confirm/);
 s.saveDeadline('avery',d.id,deadline({dueDate:'2026-12-09',confirmed:true}));
 assert.equal(w(s).deadlineDetail(d.id).completed,false);
 assert.equal(w(s,'jordan').deadlineDetail(d.id).dueDate,'2026-12-09');
 assert.match(renderPage(w(s,'jordan'),state('notices')),/9 Dec 2026/);
 assert.ok(w(s,'jordan').search('Example reporting checkpoint').some(x=>x.kind==='deadline'&&x.id===d.id));
 assert.throws(()=>s.archiveDeadline('avery',d.id),/Confirm/);
 s.archiveDeadline('avery',d.id,{confirmed:true});
 assert.throws(()=>w(s).deadlineDetail(d.id),/outside/);
 assert.equal(w(s,'avery').deadlineDetail(d.id).status,'archived');
});
