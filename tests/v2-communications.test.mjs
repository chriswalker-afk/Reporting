test('edit controls render only when authorised; old snapshots remain readable and persisted writes survive reload',()=>{
 const s=create();
 assert.match(renderPage(w(s),state('notices')),/data-action="new-notice"/);
 assert.doesNotMatch(renderPage(w(s),state('notices')),/data-action="new-deadline"/);
 assert.match(renderPage(w(s,'avery'),state('notices')),/data-action="new-deadline"/);
 assert.match(renderDetail(w(s),{kind:'notice-form',id:''}),/name="requiresAcknowledgement"/);
 assert.throws(()=>renderDetail(w(s),{kind:'deadline-form',id:''}),/cannot edit/);
 assert.match(renderDetail(w(s,'avery'),{kind:'deadline-form',id:''}),/name="dueDate"/);
 const old=createDemoData();
 for(const n of old.notices)for(const k of ['archived','pinned','requiresAcknowledgement','version','acknowledgements','links'])delete n[k];
 for(const d of old.deadlines)for(const k of ['archived','event','details','completions'])delete d[k];
 assert.deepEqual(validateData(old),[]);
 const map=new Map([[STORAGE_KEY,JSON.stringify(old)]]),storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v)};
 const persisted=createStore({storage});persisted.saveNotice('sam',null,notice());
 const n=find(persisted,'notices','Example faculty update');
 persisted.acknowledgeNotice('jordan',n.id);
 assert.equal(w(createStore({storage}),'jordan').noticeDetail(n.id).acknowledged,true);
});
