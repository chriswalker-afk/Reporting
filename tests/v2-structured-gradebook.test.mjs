import test from 'node:test';
import assert from 'node:assert/strict';
import {createStore} from '../v2/store.mjs';
import {createWorkspace} from '../v2/workspace.mjs';
import {renderPage} from '../v2/views.mjs';
import {canEnter,canEditStructured,gradebookColumns,draftFromResult,draftValue,editDraftItem,editDraftStatus,decodeDraft,structuredPreview,liveSummary,blockEntries} from '../v2/gradebook-entry.mjs';
const cls='11-maths-1',eid='P121@11-maths',topic='11-maths-A2',qla='11-maths-A3',total='11-maths-A1';
const w=s=>createWorkspace(s,'sam','faculty'),book=s=>w(s).markbook(cls);
const state={page:'classes',classId:cls,classTab:'markbook',unitId:'',query:'',flag:'all',below:false,sorts:{}};
function setup(s,id,pupil=eid){
 const b=book(s),overview=b.overview(''),a=overview.assessments.find(x=>x.id===id),p=overview.rows.find(x=>x.enrolmentId===pupil);
 return {b,overview,a,p,r:p.results[a.id]};
}
test('expanded columns retain a single calculated summary per assessment and preserve class order',()=>{
 const s=createStore(),o=book(s).overview('');
 const compact=gradebookColumns(o);
 assert.equal(compact.length,o.assessments.length);
 assert.equal(compact.find(c=>c.assessment.id===qla).kind,'summary');
 const open=gradebookColumns(o,[topic,qla]);
 assert.deepEqual(open.filter(c=>c.assessment.id===topic).map(c=>c.item?.id??'summary'),['t1','t2','summary']);
 assert.deepEqual(open.filter(c=>c.assessment.id===qla).map(c=>c.item?.id??'summary'),['q1','q2','q3','summary']);
 assert.equal(open.length,compact.length+5);
 assert.equal(gradebookColumns(o,[total,'unknown']).length,compact.length);
 const html=renderPage(w(s),{...state,gradebookExpanded:{[cls]:[qla]}});
 assert.match(html,/data-item="q1"/);assert.match(html,/aria-expanded="true"/);
 assert.doesNotMatch(renderPage(w(s),state),/class="gradebook-cell"[^>]*data-item="q1"/);
 const ro=renderPage(createWorkspace(s,'avery','school'),{...state,gradebookExpanded:{[cls]:[qla]}});
 assert.match(ro,/gradebook-item-heading/);assert.doesNotMatch(ro,/class="gradebook-cell"/);
});
test('partial marks, absence, zero and invalid input are distinct in structured drafts',()=>{
 const s=createStore(),{a,r}=setup(s,qla);
 assert.ok(canEnter(a,r,'q1'));assert.equal(canEnter(a,r),false);
 let d=editDraftStatus(a,draftFromResult(a,r),'missing');
 d=editDraftItem(a,d,'q1','0');
 assert.equal(d.status,'present');
 let decoded=decodeDraft(a,r,d);
 assert.deepEqual(decoded.entry.marks,{q1:0});
 let p=structuredPreview(a,r,decoded.entry);
 assert.equal(p.state,'incomplete');assert.equal(p.partial,0);assert.equal(p.entered,1);assert.equal(p.grade,null);
 d=editDraftItem(a,d,'q2','11');
 assert.equal(decodeDraft(a,r,d).entry,null);
 assert.match(decodeDraft(a,r,d).errors.q2,/between/);
 d=editDraftItem(a,d,'q2','10');d=editDraftItem(a,d,'q3','14');
 p=structuredPreview(a,r,decodeDraft(a,r,d).entry);
 assert.equal(p.total,24);assert.equal(p.percent,80);assert.equal(p.state,'scored');
 const absent=editDraftStatus(a,d,'absent');
 assert.deepEqual(decodeDraft(a,r,absent).entry.marks,{});
 assert.equal(structuredPreview(a,r,decodeDraft(a,r,absent).entry).state,'absent');
 const resumed=editDraftItem(a,absent,'q2','3');
 assert.deepEqual(decodeDraft(a,r,resumed).entry.marks,{q2:3});
 assert.equal(draftValue(a,resumed,'q1'),'');
});
test('structured and total entries save atomically, preserve other items and match analytics',()=>{
 const s=createStore(),{a,r,p,b}=setup(s,qla),x=setup(s,total),before=s.snapshot();
 const d=editDraftItem(a,draftFromResult(a,r),'q1','6'),e=decodeDraft(a,r,d).entry;
 for(const item of a.items.slice(1))assert.equal(e.marks[item.id],r.marks[item.id]);
 const d2=editDraftItem(x.a,draftFromResult(x.a,x.r),'total','40'),e2=decodeDraft(x.a,x.r,d2).entry;
 const previews=new Map([[qla,structuredPreview(a,r,e)],[total,structuredPreview(x.a,x.r,e2)]]);
 const live=liveSummary(p.summary,previews,{bands:b.defaultBands});
 assert.throws(()=>s.saveGradebookBatch('sam',cls,[e2,{...e,marks:{q1:99}}],{confirmed:true}),/Invalid mark/);
 assert.deepEqual(s.snapshot(),before);
 assert.throws(()=>s.saveGradebookBatch('avery',cls,[e],{confirmed:true}),/assigned teaching staff/);
 s.saveGradebookBatch('sam',cls,[e,e2],{confirmed:true,expectedRevision:0});
 assert.deepEqual(s.analytics().resultFor(qla,eid).marks,e.marks);
 assert.equal(s.analytics().studentSummary(eid).average,live.average);
 assert.equal(s.revision(),1);
 const clear=decodeDraft(a,setup(s,qla).r,editDraftStatus(a,d,'absent')).entry;
 assert.throws(()=>s.saveGradebookBatch('sam',cls,[clear],{confirmed:true}),/Confirm clearing/);
 s.saveGradebookBatch('sam',cls,[clear],{confirmed:true,confirmClear:true});
 assert.equal(s.analytics().resultFor(qla,eid).status,'absent');
 s.setStudentExclusion('sam',qla,eid,{excluded:true,reason:'Non-comparable sitting',confirmed:true});
 assert.equal(canEditStructured(a,setup(s,qla).r),false);
 assert.throws(()=>s.saveGradebookBatch('sam',cls,[e],{confirmed:true}),/excluded results/);
});
test('paste validates each visible item maximum and never shifts through calculated totals',()=>{
 const s=createStore(),{overview}=setup(s,qla),columns=gradebookColumns(overview,[qla]),row=overview.rows.findIndex(p=>p.enrolmentId===eid);
 const col=columns.findIndex(c=>c.assessment.id===qla&&c.item?.id==='q1');
 const edits=blockEntries(overview,row,col,'0\t10\t14',columns);
 assert.equal(edits.length,3);
 assert.throws(()=>blockEntries(overview,row,col,'0\t11\t14',columns),/between/);
 assert.throws(()=>blockEntries(overview,row,col,'0\t10\t14\t30',columns),/read-only or structured/);
 assert.equal(blockEntries(overview,row,col,'0\t\tCLEAR',columns).length,2);
});
